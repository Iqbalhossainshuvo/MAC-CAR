import * as Print from 'expo-print';
import { Platform } from 'react-native';

import { escapeHtml, fmtDate, money, today } from './format';

export interface ReportSection {
  title: string;
  columns: string[];
  rows: (string | number | null | undefined)[][];
  /** Optional totals row */
  footer?: (string | number)[];
  /** Columns (by index) to right-align */
  numeric?: number[];
}

export interface ReportSpec {
  title: string;
  subtitle?: string;
  filters?: [string, string][];
  summary?: [string, string][];
  sections: ReportSection[];
}

export function reportHtml(r: ReportSpec): string {
  const kv = (pairs: [string, string][]) =>
    pairs.map(([k, v]) => `<div class="kv"><span>${escapeHtml(k)}</span><b>${escapeHtml(v)}</b></div>`).join('');

  const sections = r.sections
    .map((sec) => {
      const num = new Set(sec.numeric ?? []);
      const head = sec.columns.map((c, i) => `<th class="${num.has(i) ? 'n' : ''}">${escapeHtml(c)}</th>`).join('');
      const body = sec.rows.length
        ? sec.rows
            .map(
              (row) =>
                `<tr>${row.map((cell, i) => `<td class="${num.has(i) ? 'n' : ''}">${escapeHtml(cell ?? '-')}</td>`).join('')}</tr>`,
            )
            .join('')
        : `<tr><td colspan="${sec.columns.length}" class="empty">No records</td></tr>`;
      const foot = sec.footer
        ? `<tfoot><tr>${sec.footer.map((c, i) => `<td class="${num.has(i) ? 'n' : ''}">${escapeHtml(c)}</td>`).join('')}</tr></tfoot>`
        : '';
      return `<h2>${escapeHtml(sec.title)} <small>(${sec.rows.length})</small></h2>
        <table><thead><tr>${head}</tr></thead><tbody>${body}</tbody>${foot}</table>`;
    })
    .join('');

  return `<!doctype html><html><head><meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${escapeHtml(r.title)}</title>
<style>
  @page { margin: 14mm; }
  * { box-sizing: border-box; }
  body { font-family: -apple-system, Segoe UI, Roboto, Arial, sans-serif; color: #0f172a; font-size: 12px; margin: 0; }
  header { display: flex; justify-content: space-between; align-items: flex-end; border-bottom: 3px solid #00b8cc; padding-bottom: 8px; margin-bottom: 12px; }
  .brand { font-weight: 900; letter-spacing: 3px; font-size: 20px; color: #0b1324; }
  .brand span { color: #00a3b8; }
  h1 { font-size: 16px; margin: 4px 0 0; }
  .muted { color: #475569; font-size: 11px; }
  .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(200px, 1fr)); gap: 4px 18px; margin: 8px 0 12px; }
  .kv { display: flex; justify-content: space-between; border-bottom: 1px dotted #cbd5e1; padding: 3px 0; }
  .kv span { color: #475569; }
  .summary { background: #f1f5f9; border-radius: 6px; padding: 8px 10px; }
  h2 { font-size: 13px; margin: 16px 0 6px; color: #0b1324; border-left: 4px solid #00b8cc; padding-left: 6px; }
  h2 small { color: #64748b; font-weight: normal; }
  table { width: 100%; border-collapse: collapse; page-break-inside: auto; }
  tr { page-break-inside: avoid; }
  th { background: #0b1324; color: #fff; text-align: left; padding: 5px 6px; font-size: 11px; }
  td { border-bottom: 1px solid #e2e8f0; padding: 4px 6px; vertical-align: top; }
  tbody tr:nth-child(even) td { background: #f8fafc; }
  tfoot td { font-weight: bold; border-top: 2px solid #0b1324; }
  .n { text-align: right; white-space: nowrap; }
  .empty { text-align: center; color: #94a3b8; padding: 10px; }
  footer { margin-top: 18px; color: #94a3b8; font-size: 10px; text-align: center; }
</style></head><body>
<header>
  <div><div class="brand">MAC <span>CAR</span></div><h1>${escapeHtml(r.title)}</h1>
  ${r.subtitle ? `<div class="muted">${escapeHtml(r.subtitle)}</div>` : ''}</div>
  <div class="muted">Printed ${escapeHtml(fmtDate(today()))}</div>
</header>
${r.filters?.length ? `<div class="grid">${kv(r.filters)}</div>` : ''}
${r.summary?.length ? `<div class="grid summary">${kv(r.summary)}</div>` : ''}
${sections}
<footer>Generated by MAC CAR</footer>
</body></html>`;
}

/** Print (or save as PDF from the print dialog). */
export async function printReport(r: ReportSpec) {
  const html = reportHtml(r);
  if (Platform.OS === 'web') {
    // Print through a hidden iframe so the app page itself is not printed.
    const frame = document.createElement('iframe');
    frame.style.position = 'fixed';
    frame.style.right = '0';
    frame.style.bottom = '0';
    frame.style.width = '0';
    frame.style.height = '0';
    frame.style.border = '0';
    document.body.appendChild(frame);
    const doc = frame.contentWindow!.document;
    doc.open();
    doc.write(html);
    doc.close();
    setTimeout(() => {
      frame.contentWindow!.focus();
      frame.contentWindow!.print();
      setTimeout(() => frame.remove(), 2000);
    }, 250);
    return;
  }
  await Print.printAsync({ html });
}

export const sar = (n: number) => money(n);
